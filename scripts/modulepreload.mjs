// Writes the <link rel="modulepreload"> block of each entry page from the real import graph. With no build step the
// browser otherwise discovers the ~50 start-up modules level by level (one round trip per level on a phone's data);
// the preload list lets it ask for all of them at once. Run after adding, removing or renaming an import:
//   node scripts/modulepreload.mjs          rewrite the blocks
//   node scripts/modulepreload.mjs --check  exit 1 when a page is out of date (tests/w1-parent.test.mjs checks it too)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// Each page's start: its module entry plus the modules it always imports dynamically on the way to the first screen.
export const PAGES = {
  'index.html': ['src/ui/app.js', 'src/seed/seed-data.js', 'src/ui/screens/home.js'],
  'app/index.html': ['app/boot.js', 'src/ui/app.js', 'src/api/remote.js', 'vendor/supabase/supabase-js.esm.js', 'src/ui/screens/home.js'],
};

const STATIC = /(?:^|\n)[ \t]*(?:import|export)\s+(?:[^'"`;]*?\sfrom\s+)?['"]([^'"]+)['"]/g;

/** Every file reachable by static import/export from the roots (relative specifiers only). */
export function graph(roots) {
  const seen = new Set();
  const stack = roots.map((r) => resolve(ROOT, r));
  while (stack.length) {
    const f = stack.pop();
    if (seen.has(f)) continue;
    seen.add(f);
    for (const m of readFileSync(f, 'utf8').matchAll(STATIC)) if (m[1].startsWith('.')) stack.push(resolve(dirname(f), m[1]));
  }
  return [...seen];
}

const START = '<!-- modulepreload: generated by scripts/modulepreload.mjs, do not edit by hand -->';
const END = '<!-- /modulepreload -->';

/** The generated block for one page (paths relative to the page, sorted). */
export function block(page) {
  const dir = dirname(resolve(ROOT, page));
  const hrefs = graph(PAGES[page]).map((f) => { const r = relative(dir, f).split('\\').join('/'); return r.startsWith('.') ? r : `./${r}`; }).sort();
  return [START, ...hrefs.map((h) => `  <link rel="modulepreload" href="${h}">`), `  ${END}`].join('\n');
}

function update(page, check) {
  const file = resolve(ROOT, page);
  const html = readFileSync(file, 'utf8');
  const want = block(page);
  const at = html.indexOf(START);
  const next = at >= 0
    ? html.slice(0, at) + want + html.slice(html.indexOf(END, at) + END.length)
    : html.replace('</head>', `  ${want}\n</head>`);
  if (next === html) return true;
  if (check) { console.error(`${page}: the modulepreload list is out of date; run node scripts/modulepreload.mjs`); return false; }
  writeFileSync(file, next);
  console.log(`${page}: modulepreload list written`);
  return true;
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const check = process.argv.includes('--check');
  const ok = Object.keys(PAGES).map((p) => update(p, check)).every(Boolean);
  if (!ok) process.exit(1);
}
